#!/usr/bin/env python3
"""Rank local models by how cheap they are to serve, using only repo records.

Every number in the output is computed from data/models/*.json. Nothing here is
measured or estimated independently, so the doc can cite record ids and stay
inside the repo's rule that docs never introduce a number that is not in a
record.

The ranking is about *decode cost*, which for a single user is dominated by how
many bytes of weights and KV state are read per token:

    bytes_per_token = active_params_b * 1e9 * bytes_per_weight
                    + kv_cache_bytes_per_token * context_tokens

Lower is better. Active params rather than total params, because a MoE model
only reads the experts it routes to. That is the whole reason a 671B model can
be cheaper to serve than a 70B one.

Usage:
    python tools/rank_models.py                 # markdown to stdout
    python tools/rank_models.py --context 8192  # KV cost at a longer context
    python tools/rank_models.py --top 15
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
MODELS = ROOT / "data" / "models"

# Q4 is the deployment that actually gets run locally. bf16 is kept only as a
# reference for what the model costs before quantizing.
BYTES_PER_WEIGHT = {"q4": 0.5, "q8": 1.0, "bf16": 2.0}


def load() -> list[dict]:
    out = []
    for f in sorted(MODELS.glob("*.json")):
        try:
            rec = json.loads(f.read_text(encoding="utf-8"))
        except json.JSONDecodeError:
            continue
        if isinstance(rec, dict):
            rec["_rid"] = f"models/{f.stem}"
            out.append(rec)
    return out


def eligible(rec: dict) -> bool:
    """A model can be ranked only when the two inputs to the cost exist and it
    can actually be downloaded."""
    if rec.get("open_weights") is not True:
        return False
    if not rec.get("active_params_b"):
        return False
    if not rec.get("kv_cache_bytes_per_token"):
        return False
    return True


def cost(rec: dict, quant: str, context: int) -> float:
    weights = rec["active_params_b"] * 1e9 * BYTES_PER_WEIGHT[quant]
    kv = rec["kv_cache_bytes_per_token"] * context
    return weights + kv


def gb(n: float) -> str:
    return f"{n / 1e9:.2f}"


def row(rec: dict, context: int) -> dict:
    c4 = cost(rec, "q4", context)
    return {
        "rid": rec["_rid"],
        "name": rec["name"],
        "arch": rec.get("architecture") or "?",
        "total": rec.get("params_b"),
        "active": rec["active_params_b"],
        "kv": rec["kv_cache_bytes_per_token"],
        "ctx": rec.get("max_position_embeddings"),
        "license": rec.get("license") or "unstated",
        "q4_gb": c4 / 1e9,
        "bf16_gb": cost(rec, "bf16", context) / 1e9,
    }


def render(rows: list[dict], context: int, skipped: int) -> str:
    lines = []
    lines.append("# Local model ranking")
    lines.append("")
    lines.append("Generated by `tools/rank_models.py`. Do not edit by hand;")
    lines.append("change the records and regenerate.")
    lines.append("")
    lines.append("## What is being ranked")
    lines.append("")
    lines.append("Decode reads two things per token: the active weights, and the")
    lines.append("KV state for the context so far. This ranks models by the sum,")
    lines.append(f"at Q4 (0.5 bytes/weight) and a {context:,}-token context:")
    lines.append("")
    lines.append("    GB/token = active_params_b x 0.5  +  kv_cache_bytes_per_token x context / 1e9")
    lines.append("")
    lines.append("Active params, not total. A MoE model only reads the experts it")
    lines.append("routes to, so a 671B model can cost less per token than a 70B one.")
    lines.append("The KV term is why two models with identical active params rank")
    lines.append("differently: MLA and GQA change how much state each token keeps.")
    lines.append("")
    lines.append("This is a cost ranking, not a quality ranking. It says nothing")
    lines.append("about how good the model is, only how much memory bandwidth a")
    lines.append("token consumes. A model absent from this list is missing")
    lines.append("`active_params_b` or `kv_cache_bytes_per_token`, not judged unworthy.")
    lines.append("")
    lines.append(f"{len(rows)} models ranked, {skipped} open-weight models excluded")
    lines.append("for missing one of those two fields.")
    lines.append("")
    lines.append("## Ranking")
    lines.append("")
    lines.append("| Rank | Model | Arch | Total B | Active B | KV B/token | Q4 GB @ ctx | License |")
    lines.append("| --- | --- | --- | --- | --- | --- | --- | --- |")
    for i, r in enumerate(rows, 1):
        total = f"{r['total']:g}" if r["total"] else "—"
        lines.append(
            f"| {i} | [[{r['rid']}]] | {r['arch']} | {total} | {r['active']:g} "
            f"| {r['kv']:,} | {r['q4_gb']:.2f} | {r['license']} |"
        )
    lines.append("")
    lines.append("## How to read the top of the list")
    lines.append("")
    lines.append("The cheapest entries are small models. That is correct and not")
    lines.append("very useful on its own — a 1B model is cheap because it cannot")
    lines.append("do much. The interesting comparisons are within a size band:")
    lines.append("")
    lines.append("- **MoE versus dense at similar active params.** If a MoE model")
    lines.append("  ranks near a dense model a fraction of its total size, you are")
    lines.append("  getting the large model's capacity at the small model's decode")
    lines.append("  cost. That gap is the reason to run MoE locally.")
    lines.append("- **KV cost at long context.** Re-run with `--context 32768`.")
    lines.append("  Models whose rank collapses have an expensive KV layout, and")
    lines.append("  that is where KV quantisation or MLA earns its place.")
    lines.append("- **bf16 column in the raw output.** Pass `--show-bf16` to see")
    lines.append("  what the same model costs before quantising. The ratio tells you")
    lines.append("  how much of the deployability is the quantisation's doing.")
    lines.append("")
    return "\n".join(lines)


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--context", type=int, default=4096)
    ap.add_argument("--top", type=int, default=0, help="limit rows (0 = all)")
    ap.add_argument("--min-active", type=float, default=0.0)
    ap.add_argument("--max-active", type=float, default=1e9)
    args = ap.parse_args()

    all_models = load()
    kept, skipped = [], 0
    for rec in all_models:
        if rec.get("open_weights") is not True:
            continue
        if not eligible(rec):
            skipped += 1
            continue
        if not (args.min_active <= rec["active_params_b"] <= args.max_active):
            continue
        kept.append(row(rec, args.context))

    kept.sort(key=lambda r: (r["q4_gb"], r["name"]))
    if args.top:
        kept = kept[: args.top]

    sys.stdout.write(render(kept, args.context, skipped))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
