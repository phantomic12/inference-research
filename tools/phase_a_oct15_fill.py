def w(rel, rec):
    p = os.path.join(ROOT, rel)
    if os.path.exists(p):
        print("SKIP (exists)", rel)
        return False
    os.makedirs(os.path.dirname(p), exist_ok=True)
    with open(p, "w") as fh:
        json.dump(rec, fh, indent=2, sort_keys=False)
        fh.write("\n")
    print("WROTE", rel)
    return True


